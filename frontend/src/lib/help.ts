export function resolveHelpTopic(pathname: string): HelpTopic {
  const p = String(pathname || "");
  if (p === "/" || p.startsWith("/calculator")) return "calculator";
  if (p === "/app") return "invoices";
  if (p === "/create") return "invoice_create";
  if (p.startsWith("/invoices/")) return "invoice_detail";

  if (p.startsWith("/nsi/uoms")) return "nsi_uoms";
  if (p.startsWith("/nsi/item-categories")) return "nsi_categories";
  if (p.startsWith("/nsi/counterparties")) return "nsi_counterparties";
  if (p.startsWith("/nsi/items")) return "nsi_items";
  if (p.startsWith("/nsi/packages")) return "nsi_packages";
  if (p.startsWith("/nsi/rules/new") || p.startsWith("/nsi/rules/item/") || p.startsWith("/nsi/rules/category/") || p.startsWith("/nsi/rules/global/")) return "nsi_rule_wizard";
  if (p.startsWith("/nsi/rules")) return "nsi_rules";

  if (p.startsWith("/admin/console")) return "admin_console";
  if (p.startsWith("/feedback/inbox")) return "feedback_inbox";
  if (p === "/feedback") return "feedback_form";
  return "general";
}
